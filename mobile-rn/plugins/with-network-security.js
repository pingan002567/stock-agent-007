// Expo config plugin：让自建后端的 http:// 明文与自签 HTTPS 可用。
// 与 iOS 端 `TrustingURLSessionDelegate` 对齐（iOS 无条件信任 server trust）。
//
// 安全提示（对应技术选型文档 4.7 / 7.5）：
//   - 当前放行明文 http（base-config cleartextTrafficPermitted=true）
//     并信任「系统 + 用户」CA。
//   - 自签 HTTPS 两种接法（二选一）：
//       1) 把服务器 CA 安装为设备的「用户 CA」（<certificates src="user"/> 已信任）；
//       2) 把 CA 打进 res/raw 并加 <certificates src="@raw/ca"/>（更严谨）。
//   - 不要把「全局 trust-all」打进 release。

const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by ./plugins/with-network-security.js -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withNetworkSecurity(config) {
  config = withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults?.manifest?.application?.[0];
    if (application) {
      application.$ = application.$ || {};
      application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    }
    return cfg;
  });

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml'
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'network_security_config.xml'), NETWORK_SECURITY_CONFIG);
      return cfg;
    },
  ]);

  return config;
}

module.exports = withNetworkSecurity;
